-- Stage 2 operational foundations: suppliers, raw materials, production and offline sales.
CREATE TABLE IF NOT EXISTS public.suppliers (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), supplier_name text NOT NULL, contact_person text, phone text, email text, address text, notes text,
 is_active boolean NOT NULL DEFAULT true, created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.raw_materials (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), material_name text NOT NULL UNIQUE, unit text NOT NULL DEFAULT 'kg',
 quantity_on_hand numeric(14,3) NOT NULL DEFAULT 0 CHECK(quantity_on_hand>=0), average_unit_cost numeric(14,2) NOT NULL DEFAULT 0 CHECK(average_unit_cost>=0),
 reorder_level numeric(14,3) NOT NULL DEFAULT 0 CHECK(reorder_level>=0), is_active boolean NOT NULL DEFAULT true,
 created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.supplier_purchases (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), purchase_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 supplier_id uuid NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT, purchase_date date NOT NULL DEFAULT CURRENT_DATE,
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','pending_approval','approved','received','cancelled')),
 total_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK(total_amount>=0), notes text, received_at timestamptz,
 received_by uuid REFERENCES auth.users(id), created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.supplier_purchase_items (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), purchase_id uuid NOT NULL REFERENCES public.supplier_purchases(id) ON DELETE RESTRICT,
 material_id uuid NOT NULL REFERENCES public.raw_materials(id) ON DELETE RESTRICT, quantity numeric(14,3) NOT NULL CHECK(quantity>0),
 unit_cost numeric(14,2) NOT NULL CHECK(unit_cost>=0), line_total numeric(14,2) GENERATED ALWAYS AS (round(quantity*unit_cost,2)) STORED
);
CREATE TABLE IF NOT EXISTS public.supplier_payments (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), purchase_id uuid NOT NULL REFERENCES public.supplier_purchases(id) ON DELETE RESTRICT,
 amount numeric(14,2) NOT NULL CHECK(amount>0), payment_date date NOT NULL DEFAULT CURRENT_DATE,
 payment_method text NOT NULL DEFAULT 'bank_transfer' CHECK(payment_method IN ('cash','bank_transfer','pos','wallet','other')),
 reference text, financial_transaction_id uuid UNIQUE REFERENCES public.financial_transactions(id) ON DELETE RESTRICT,
 created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.production_batches (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), batch_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT, variant_id uuid NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
 production_date date NOT NULL DEFAULT CURRENT_DATE, expiry_date date, status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','pending_approval','approved','completed','cancelled')),
 planned_quantity integer NOT NULL DEFAULT 0 CHECK(planned_quantity>=0), produced_quantity integer NOT NULL DEFAULT 0 CHECK(produced_quantity>=0),
 wastage_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK(wastage_quantity>=0), production_cost numeric(14,2) NOT NULL DEFAULT 0 CHECK(production_cost>=0),
 production_staff text, overhead_cost numeric(14,2) NOT NULL DEFAULT 0 CHECK(overhead_cost>=0), notes text,
 completed_at timestamptz, completed_by uuid REFERENCES auth.users(id), created_by uuid REFERENCES auth.users(id),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), CHECK(expiry_date IS NULL OR expiry_date>=production_date)
);
CREATE TABLE IF NOT EXISTS public.production_batch_materials (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), batch_id uuid NOT NULL REFERENCES public.production_batches(id) ON DELETE RESTRICT,
 material_id uuid NOT NULL REFERENCES public.raw_materials(id) ON DELETE RESTRICT, quantity_used numeric(14,3) NOT NULL CHECK(quantity_used>0),
 unit_cost numeric(14,2) NOT NULL CHECK(unit_cost>=0), line_cost numeric(14,2) GENERATED ALWAYS AS (round(quantity_used*unit_cost,2)) STORED
);
CREATE TABLE IF NOT EXISTS public.manual_sales (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), sale_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 customer_name text NOT NULL, customer_phone text, sales_channel text NOT NULL CHECK(sales_channel IN ('walk_in','retail','wholesale','phone','whatsapp','social_media','market','other')),
 sale_date date NOT NULL DEFAULT CURRENT_DATE, status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','pending_approval','approved','completed','partially_returned','returned','cancelled')),
 total_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK(total_amount>=0), amount_paid numeric(14,2) NOT NULL DEFAULT 0 CHECK(amount_paid>=0),
 notes text, supplied_at timestamptz, supplied_by uuid REFERENCES auth.users(id), created_by uuid REFERENCES auth.users(id),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.manual_sale_items (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), sale_id uuid NOT NULL REFERENCES public.manual_sales(id) ON DELETE RESTRICT,
 product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT, variant_id uuid NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
 quantity integer NOT NULL CHECK(quantity>0), unit_price numeric(14,2) NOT NULL CHECK(unit_price>=0),
 line_total numeric(14,2) GENERATED ALWAYS AS (round(quantity*unit_price,2)) STORED
);
CREATE TABLE IF NOT EXISTS public.manual_sale_payments (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), sale_id uuid NOT NULL REFERENCES public.manual_sales(id) ON DELETE RESTRICT,
 amount numeric(14,2) NOT NULL CHECK(amount>0), payment_date date NOT NULL DEFAULT CURRENT_DATE,
 payment_method text NOT NULL DEFAULT 'cash' CHECK(payment_method IN ('cash','bank_transfer','pos','wallet','other')),
 reference text, financial_transaction_id uuid UNIQUE REFERENCES public.financial_transactions(id) ON DELETE RESTRICT,
 created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.manual_sale_returns (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), sale_id uuid NOT NULL REFERENCES public.manual_sales(id) ON DELETE RESTRICT,
 return_date date NOT NULL DEFAULT CURRENT_DATE, reason text NOT NULL, refund_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK(refund_amount>=0),
 status text NOT NULL DEFAULT 'pending_approval' CHECK(status IN ('pending_approval','approved','rejected','completed')),
 financial_transaction_id uuid UNIQUE REFERENCES public.financial_transactions(id) ON DELETE RESTRICT,
 created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.manual_sale_return_items (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), return_id uuid NOT NULL REFERENCES public.manual_sale_returns(id) ON DELETE RESTRICT,
 sale_item_id uuid NOT NULL REFERENCES public.manual_sale_items(id) ON DELETE RESTRICT, quantity integer NOT NULL CHECK(quantity>0)
);
CREATE TABLE IF NOT EXISTS public.raw_material_movements (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), material_id uuid NOT NULL REFERENCES public.raw_materials(id) ON DELETE RESTRICT,
 movement_type text NOT NULL CHECK(movement_type IN ('purchase_received','production_consumed','adjustment','return')),
 quantity_change numeric(14,3) NOT NULL CHECK(quantity_change<>0), reason text,
 purchase_id uuid REFERENCES public.supplier_purchases(id) ON DELETE RESTRICT,
 batch_id uuid REFERENCES public.production_batches(id) ON DELETE RESTRICT,
 created_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now()
);
