CREATE OR REPLACE FUNCTION public.stage2_receive_purchase(p_purchase_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE v_purchase public.supplier_purchases%ROWTYPE; v_item record; v_uid uuid:=auth.uid();
BEGIN
 IF v_uid IS NULL OR NOT private.has_admin_role(ARRAY['owner']::text[]) THEN RAISE EXCEPTION 'Only the Founder can receive approved purchases.'; END IF;
 SELECT * INTO v_purchase FROM public.supplier_purchases WHERE id=p_purchase_id FOR UPDATE;
 IF NOT FOUND OR v_purchase.status<>'approved' THEN RAISE EXCEPTION 'Purchase must be approved by the Founder before receipt.'; END IF;
 FOR v_item IN SELECT * FROM public.supplier_purchase_items WHERE purchase_id=p_purchase_id LOOP
  UPDATE public.raw_materials SET average_unit_cost=CASE WHEN quantity_on_hand+v_item.quantity>0 THEN round(((quantity_on_hand*average_unit_cost)+(v_item.quantity*v_item.unit_cost))/(quantity_on_hand+v_item.quantity),2) ELSE v_item.unit_cost END,
   quantity_on_hand=quantity_on_hand+v_item.quantity,updated_at=now() WHERE id=v_item.material_id;
  INSERT INTO public.raw_material_movements(material_id,movement_type,quantity_change,reason,purchase_id,created_by)
   VALUES(v_item.material_id,'purchase_received',v_item.quantity,'Received supplier purchase #'||v_purchase.purchase_number,p_purchase_id,v_uid);
 END LOOP;
 UPDATE public.supplier_purchases SET status='received',received_at=now(),received_by=v_uid,updated_at=now() WHERE id=p_purchase_id;
 INSERT INTO public.admin_audit_logs(actor_user_id,action,resource_type,resource_id,details)
  VALUES(v_uid,'receive_supplier_purchase','supplier_purchase',p_purchase_id::text,jsonb_build_object('purchase_number',v_purchase.purchase_number,'total_amount',v_purchase.total_amount));
 RETURN jsonb_build_object('success',true,'purchase_number',v_purchase.purchase_number);
END $function$;

CREATE OR REPLACE FUNCTION public.stage2_complete_production(p_batch_id uuid,p_produced_quantity integer,p_wastage numeric DEFAULT 0)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE v_batch public.production_batches%ROWTYPE; v_item record; v_cost numeric(14,2):=0; v_uid uuid:=auth.uid();
BEGIN
 IF v_uid IS NULL OR NOT private.has_admin_role(ARRAY['owner']::text[]) THEN RAISE EXCEPTION 'Only the Founder can approve and complete production.'; END IF;
 IF p_produced_quantity<=0 OR p_wastage<0 THEN RAISE EXCEPTION 'Enter a valid produced quantity and non-negative wastage.'; END IF;
 SELECT * INTO v_batch FROM public.production_batches WHERE id=p_batch_id FOR UPDATE;
 IF NOT FOUND OR v_batch.status<>'approved' THEN RAISE EXCEPTION 'Batch must be approved by the Founder before completion.'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.production_batch_materials WHERE batch_id=p_batch_id) THEN RAISE EXCEPTION 'Add at least one raw material before completing this batch.'; END IF;
 FOR v_item IN SELECT * FROM public.production_batch_materials WHERE batch_id=p_batch_id LOOP
  UPDATE public.raw_materials SET quantity_on_hand=quantity_on_hand-v_item.quantity_used,updated_at=now() WHERE id=v_item.material_id AND quantity_on_hand>=v_item.quantity_used;
  IF NOT FOUND THEN RAISE EXCEPTION 'Insufficient raw material stock for material %.',v_item.material_id; END IF;
  INSERT INTO public.raw_material_movements(material_id,movement_type,quantity_change,reason,batch_id,created_by)
   VALUES(v_item.material_id,'production_consumed',-v_item.quantity_used,'Consumed for batch #'||v_batch.batch_number,p_batch_id,v_uid);
  v_cost:=v_cost+v_item.line_cost;
 END LOOP;
 UPDATE public.product_variants SET stock_quantity=stock_quantity+p_produced_quantity WHERE id=v_batch.variant_id;
 INSERT INTO public.inventory_movements(variant_id,movement_type,quantity_change,reason,created_by)
  VALUES(v_batch.variant_id,'production',p_produced_quantity,'Finished production batch #'||v_batch.batch_number,v_uid);
 UPDATE public.production_batches SET status='completed',produced_quantity=p_produced_quantity,wastage_quantity=p_wastage,
  production_cost=v_cost+v_batch.overhead_cost,completed_at=now(),completed_by=v_uid,updated_at=now() WHERE id=p_batch_id;
 INSERT INTO public.admin_audit_logs(actor_user_id,action,resource_type,resource_id,details)
  VALUES(v_uid,'complete_production_batch','production_batch',p_batch_id::text,jsonb_build_object('batch_number',v_batch.batch_number,'produced_quantity',p_produced_quantity,'wastage',p_wastage,'raw_material_cost',v_cost,'overhead_cost',v_batch.overhead_cost,'total_production_cost',v_cost+v_batch.overhead_cost,'production_staff',v_batch.production_staff));
 RETURN jsonb_build_object('success',true,'batch_number',v_batch.batch_number,'production_cost',v_cost+v_batch.overhead_cost);
END $function$;

CREATE OR REPLACE FUNCTION public.stage2_complete_manual_sale(p_sale_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE v_sale public.manual_sales%ROWTYPE; v_item record; v_uid uuid:=auth.uid();
BEGIN
 IF v_uid IS NULL OR NOT private.has_admin_role(ARRAY['owner']::text[]) THEN RAISE EXCEPTION 'Only the Founder can approve and complete manual sales.'; END IF;
 SELECT * INTO v_sale FROM public.manual_sales WHERE id=p_sale_id FOR UPDATE;
 IF NOT FOUND OR v_sale.status<>'approved' THEN RAISE EXCEPTION 'Sale must be approved by the Founder before goods are supplied.'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.manual_sale_items WHERE sale_id=p_sale_id) THEN RAISE EXCEPTION 'Add at least one sale item.'; END IF;
 FOR v_item IN SELECT * FROM public.manual_sale_items WHERE sale_id=p_sale_id LOOP
  UPDATE public.product_variants SET stock_quantity=stock_quantity-v_item.quantity WHERE id=v_item.variant_id AND stock_quantity>=v_item.quantity;
  IF NOT FOUND THEN RAISE EXCEPTION 'Insufficient stock for sale item %.',v_item.id; END IF;
  INSERT INTO public.inventory_movements(variant_id,movement_type,quantity_change,reason,created_by)
   VALUES(v_item.variant_id,'manual_sale',-v_item.quantity,'Manual sale #'||v_sale.sale_number,v_uid);
 END LOOP;
 UPDATE public.manual_sales SET status='completed',supplied_at=now(),supplied_by=v_uid,updated_at=now() WHERE id=p_sale_id;
 INSERT INTO public.admin_audit_logs(actor_user_id,action,resource_type,resource_id,details)
  VALUES(v_uid,'complete_manual_sale','manual_sale',p_sale_id::text,jsonb_build_object('sale_number',v_sale.sale_number,'total_amount',v_sale.total_amount));
 RETURN jsonb_build_object('success',true,'sale_number',v_sale.sale_number);
END $function$;
